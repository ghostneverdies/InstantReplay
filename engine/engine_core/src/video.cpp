    std::unique_ptr<MfEncoder> MfEncoder::create(MfCodec codec, MfVendor vendor, const GpuContext *gpu, int w, int h,
                                                 int fps, uint32_t bps, Rate rate, Preset preset,
                                                 ObjectPool<PacketRef> *packets, std::string *err)
    {
        auto fail = [&](const char *what, HRESULT hr) -> std::unique_ptr<MfEncoder>
        {
            char buf[160];
            std::snprintf(buf, sizeof(buf), "Media Foundation %s failed (0x%08X)", what, (unsigned)hr);
            if (err)
                *err = buf;
            return nullptr;
        };
        MfRuntime &rt = mf_runtime();
        if (FAILED(rt.com_hr))
            return fail("COM initialization", rt.com_hr);
        if (FAILED(rt.mf_hr))
            return fail("startup", rt.mf_hr);
        w &= ~1;
        h &= ~1;
        if (w < 2 || h < 2)
            return fail("output size", E_INVALIDARG);

        IMFActivate **list = nullptr;
        UINT32 count = 0;
        HRESULT hr = Impl::enumerate_mfts(codec, vendor, gpu, &list, &count);
        if (FAILED(hr) || count == 0)
        {
            if (list)
                CoTaskMemFree(list);
            char buf[192];
            std::snprintf(buf, sizeof(buf), "Media Foundation %s %s MFT is not available (0x%08X)",
                          mf_vendor_name(vendor), mf_codec_name(codec),
                          (unsigned)(FAILED(hr) ? hr : MF_E_TOPO_CODEC_NOT_FOUND));
            if (err)
                *err = buf;
            return nullptr;
        }

        // A DXGI device manager lets a matching hardware MFT consume our NV12 textures directly.
        // Mismatched transforms (common on hybrid systems) stay in system-memory mode.
        LUID luid = {};
        const bool have_luid = gpu && gpu->dev && device_luid(gpu->dev.Get(), &luid);
        ComPtr<IMFDXGIDeviceManager> manager;
        UINT32 reset_token = 0;
        const bool manager_ready =
            have_luid && SUCCEEDED(MFCreateDXGIDeviceManager(&reset_token, &manager)) && manager &&
            SUCCEEDED(manager->ResetDevice(gpu->dev.Get(), reset_token));

        auto enc = std::unique_ptr<MfEncoder>(new MfEncoder());
        HRESULT last = E_FAIL;
        bool created = false;
        for (UINT32 i = 0; i < count && !created; ++i)
        {
            const bool matching = manager_ready && activate_matches_luid(list[i], &luid);
            // Try DXGI input first on a matching MFT; if the transform rejects it, retry the
            // same MFT with system-memory input before moving on to another vendor.
            const int attempts = matching ? 2 : 1;
            for (int attempt = 0; attempt < attempts && !created; ++attempt)
            {
                const bool use_texture = matching && attempt == 0;
                auto impl = std::make_unique<Impl>();
                impl->w = w;
                impl->h = h;
                impl->hevc = codec == MfCodec::Hevc;
                impl->av1 = codec == MfCodec::Av1;
                impl->codec = codec;
                impl->vendor = vendor;
                impl->packets = packets;
                impl->frame_dur = SECOND_100NS / std::max(1, fps);
                hr = list[i]->ActivateObject(IID_PPV_ARGS(&impl->mft));
                if (FAILED(hr) || !impl->mft)
                {
                    last = FAILED(hr) ? hr : E_NOINTERFACE;
                    continue;
                }

                ComPtr<IMFAttributes> attrs;
                if (SUCCEEDED(impl->mft->GetAttributes(&attrs)) && attrs)
                {
                    UINT32 is_async = 0;
                    if (SUCCEEDED(attrs->GetUINT32(MF_TRANSFORM_ASYNC, &is_async)) && is_async)
                    {
                        impl->async = true;
                        attrs->SetUINT32(MF_TRANSFORM_ASYNC_UNLOCK, TRUE);
                        impl->mft.As(&impl->events);
                    }
                    attrs->SetUINT32(MF_LOW_LATENCY, TRUE);
                }
                if (impl->async && !impl->events)
                {
                    last = E_NOINTERFACE;
                    continue;
                }

                if (use_texture)
                {
                    hr = impl->mft->ProcessMessage(MFT_MESSAGE_SET_D3D_MANAGER, (ULONG_PTR)manager.Get());
                    if (FAILED(hr))
                    {
                        last = hr;
                        continue;
                    }
                    impl->manager = manager;
                    impl->texture = true;
                }

                impl->mft.As(&impl->api);
                if (impl->api)
                {
                    set_u32(impl->api.Get(), CODECAPI_AVEncCommonRateControlMode,
                            rate == Rate::Cbr ? eAVEncCommonRateControlMode_CBR
                                              : eAVEncCommonRateControlMode_PeakConstrainedVBR);
                    set_u32(impl->api.Get(), CODECAPI_AVEncCommonMeanBitRate, bps);
                    if (rate == Rate::Vbr)
                        set_u32(impl->api.Get(), CODECAPI_AVEncCommonMaxBitRate, (uint32_t)((uint64_t)bps * 3 / 2));
                    set_u32(impl->api.Get(), CODECAPI_AVEncMPVGOPSize, (uint32_t)(fps * 2));
                    set_u32(impl->api.Get(), CODECAPI_AVEncMPVDefaultBPictureCount, 0);
                    set_bool(impl->api.Get(), CODECAPI_AVLowLatencyMode, true);
                    set_u32(impl->api.Get(), CODECAPI_AVEncCommonQualityVsSpeed,
                            (uint32_t)((int)preset * 100 / 6));
                }

                const bool highdef = w >= 1280 || h > 576;
                ComPtr<IMFMediaType> out_t;
                if (FAILED(MFCreateMediaType(&out_t)) || !out_t)
                {
                    last = E_OUTOFMEMORY;
                    continue;
                }
                out_t->SetGUID(MF_MT_MAJOR_TYPE, MFMediaType_Video);
                out_t->SetGUID(MF_MT_SUBTYPE, mf_codec_subtype(codec));
                out_t->SetUINT32(MF_MT_AVG_BITRATE, bps);
                MFSetAttributeSize(out_t.Get(), MF_MT_FRAME_SIZE, w, h);
                MFSetAttributeRatio(out_t.Get(), MF_MT_FRAME_RATE, fps, 1);
                MFSetAttributeRatio(out_t.Get(), MF_MT_PIXEL_ASPECT_RATIO, 1, 1);
                out_t->SetUINT32(MF_MT_INTERLACE_MODE, MFVideoInterlace_Progressive);
                if (codec != MfCodec::Av1)
                    out_t->SetUINT32(MF_MT_MPEG2_PROFILE,
                                     codec == MfCodec::Hevc ? (UINT32)eAVEncH265VProfile_Main_420_8
                                                            : (UINT32)eAVEncH264VProfile_High);
                out_t->SetUINT32(MF_MT_VIDEO_NOMINAL_RANGE, MFNominalRange_16_235);
                out_t->SetUINT32(MF_MT_YUV_MATRIX, highdef ? MFVideoTransferMatrix_BT709 : MFVideoTransferMatrix_BT601);
                out_t->SetUINT32(MF_MT_VIDEO_PRIMARIES, highdef ? MFVideoPrimaries_BT709
                                                                : MFVideoPrimaries_SMPTE170M);
                out_t->SetUINT32(MF_MT_TRANSFER_FUNCTION, MFVideoTransFunc_709);
                hr = impl->mft->SetOutputType(0, out_t.Get(), 0);
                if (FAILED(hr))
                {
                    last = hr;
                    continue;
                }

                ComPtr<IMFMediaType> in_t;
                if (FAILED(MFCreateMediaType(&in_t)) || !in_t)
                {
                    last = E_OUTOFMEMORY;
                    continue;
                }
                in_t->SetGUID(MF_MT_MAJOR_TYPE, MFMediaType_Video);
                in_t->SetGUID(MF_MT_SUBTYPE, MFVideoFormat_NV12);
                MFSetAttributeSize(in_t.Get(), MF_MT_FRAME_SIZE, w, h);
                MFSetAttributeRatio(in_t.Get(), MF_MT_FRAME_RATE, fps, 1);
                MFSetAttributeRatio(in_t.Get(), MF_MT_PIXEL_ASPECT_RATIO, 1, 1);
                in_t->SetUINT32(MF_MT_INTERLACE_MODE, MFVideoInterlace_Progressive);
                in_t->SetUINT32(MF_MT_VIDEO_NOMINAL_RANGE, MFNominalRange_16_235);
                in_t->SetUINT32(MF_MT_YUV_MATRIX, highdef ? MFVideoTransferMatrix_BT709 : MFVideoTransferMatrix_BT601);
                in_t->SetUINT32(MF_MT_VIDEO_PRIMARIES, highdef ? MFVideoPrimaries_BT709
                                                                : MFVideoPrimaries_SMPTE170M);
                in_t->SetUINT32(MF_MT_TRANSFER_FUNCTION, MFVideoTransFunc_709);
                hr = impl->mft->SetInputType(0, in_t.Get(), 0);
                if (FAILED(hr))
                {
                    last = hr;
                    continue;
                }

                MFT_OUTPUT_STREAM_INFO info = {};
                if (SUCCEEDED(impl->mft->GetOutputStreamInfo(0, &info)))
                {
                    impl->provides_samples = (info.dwFlags & (MFT_OUTPUT_STREAM_PROVIDES_SAMPLES |
                                                              MFT_OUTPUT_STREAM_CAN_PROVIDE_SAMPLES)) != 0;
                    impl->out_size = std::max<DWORD>(info.cbSize, 1u << 20);
                }
                else
                {
                    impl->out_size = std::max<DWORD>((DWORD)(w * h), 1u << 20);
                }

                impl->seq_header = read_seq_header(impl->mft.Get());

                impl->mft->ProcessMessage(MFT_MESSAGE_COMMAND_FLUSH, 0);
                impl->mft->ProcessMessage(MFT_MESSAGE_NOTIFY_BEGIN_STREAMING, 0);
                impl->mft->ProcessMessage(MFT_MESSAGE_NOTIFY_START_OF_STREAM, 0);
                enc->p_ = std::move(impl);
                created = true;
            }
        }
        for (UINT32 i = 0; i < count; ++i)
            list[i]->Release();
        CoTaskMemFree(list);
        if (!created)
        {
            enc->p_ = std::make_unique<Impl>();
            enc->p_->packets = packets;
            enc->p_->init_hr = last;
            return fail("encoder setup", last);
        }
        return enc;
    }

    bool MfEncoder::encode_texture(ID3D11Texture2D *nv12, int64_t pts100ns, bool idr,
                                   std::vector<Ref<PacketRef>> &out, std::string *err)
    {
        if (!p_ || !p_->texture || !p_->manager || !nv12)
        {
            if (err)
                *err = "this Media Foundation encoder cannot accept GPU textures";
            return false;
        }
        ComPtr<IMFMediaBuffer> mb;
        HRESULT hr = MFCreateDXGISurfaceBuffer(__uuidof(ID3D11Texture2D), nv12, 0, FALSE, &mb);
        if (FAILED(hr) || !mb)
        {
            if (err)
                *err = "MFCreateDXGISurfaceBuffer failed";
            return false;
        }
        mb->SetCurrentLength((DWORD)(p_->w * p_->h * 3 / 2));
        ComPtr<IMFSample> sample;
        if (FAILED(MFCreateSample(&sample)) || !sample)
        {
            if (err)
                *err = "Media Foundation could not allocate an input sample";
            return false;
        }
        sample->AddBuffer(mb.Get());
        sample->SetSampleDuration(p_->frame_dur);
        return p_->feed(sample.Get(), pts100ns, idr, out, err);
    }

    bool MfEncoder::encode_memory(const uint8_t *y, size_t y_stride, const uint8_t *uv, size_t uv_stride,
                                  int64_t pts100ns, bool idr, std::vector<Ref<PacketRef>> &out, std::string *err)
    {
        if (!p_)
        {
            if (err)
                *err = "Media Foundation encoder is not initialised";
            return false;
        }
        const size_t w = (size_t)p_->w, h = (size_t)p_->h;
        if (!y || !uv || w == 0 || h < 2 || y_stride < w || uv_stride < w)
        {
            if (err)
                *err = "Media Foundation input planes or strides are invalid";
            return false;
        }
        ComPtr<IMFMediaBuffer> mb;
        if (FAILED(MFCreateMemoryBuffer((DWORD)(w * h * 3 / 2), &mb)) || !mb)
        {
            if (err)
                *err = "Media Foundation could not allocate an input buffer";
            return false;
        }
        BYTE *dst = nullptr;
        if (FAILED(mb->Lock(&dst, nullptr, nullptr)) || !dst)
        {
            if (err)
                *err = "Media Foundation input buffer lock failed";
            return false;
        }
        for (size_t r = 0; r < h; ++r)
            std::memcpy(dst + r * w, y + r * y_stride, w);
        for (size_t r = 0; r < h / 2; ++r)
            std::memcpy(dst + w * h + r * w, uv + r * uv_stride, w);
        mb->Unlock();
        mb->SetCurrentLength((DWORD)(w * h * 3 / 2));
        ComPtr<IMFSample> sample;
        if (FAILED(MFCreateSample(&sample)) || !sample)
        {
            if (err)
                *err = "Media Foundation could not allocate an input sample";
            return false;
        }
        sample->AddBuffer(mb.Get());
        sample->SetSampleDuration(p_->frame_dur);
        return p_->feed(sample.Get(), pts100ns, idr, out, err);
    }

    bool MfEncoder::flush(std::vector<Ref<PacketRef>> &out, std::string *err)
    {
        if (!p_)
        {
            if (err)
                *err = "Media Foundation encoder is not initialised";
            return false;
        }
        Impl &p = *p_;
        HRESULT hr = p.mft->ProcessMessage(MFT_MESSAGE_NOTIFY_END_OF_STREAM, 0);
        if (FAILED(hr))
        {
            char m[96];
            std::snprintf(m, sizeof(m), "Media Foundation end-of-stream failed (0x%08X)", (unsigned)hr);
            if (err)
                *err = m;
            return false;
        }
        hr = p.mft->ProcessMessage(MFT_MESSAGE_COMMAND_DRAIN, 0);
        if (FAILED(hr))
        {
            char m[96];
            std::snprintf(m, sizeof(m), "Media Foundation drain failed (0x%08X)", (unsigned)hr);
            if (err)
                *err = m;
            return false;
        }
        if (!p.async)
            return p.pump(out, err, false);
        for (int i = 0; i < 400; ++i)
        { // ~2 s ceiling
            ComPtr<IMFMediaEvent> ev;
            HRESULT ehr = p.events->GetEvent(MF_EVENT_FLAG_NO_WAIT, &ev);
            if (ehr == MF_E_NO_EVENTS_AVAILABLE)
            {
                Sleep(5);
                continue;
            }
            if (FAILED(ehr))
                return true;
            MediaEventType type = MEUnknown;
            ev->GetType(&type);
            if (type == METransformHaveOutput)
            {
                if (!p.process_output(out, err, nullptr))
                    return false;
            }
            else if (type == METransformDrainComplete)
            {
                return true;
            }
        }
        return true;
    }

    int MfEncoder::kind_code() const noexcept
    {
        if (!p_)
            return KIND_UNKNOWN;
        const int hevc_base = 20; // 20..24
        const int h264_base = 30; // 30..34
        const int av1_base = 40;  // 40..44
        const int v = p_->vendor == MfVendor::Vp12   ? 1
                      : p_->vendor == MfVendor::Nvenc ? 2
                      : p_->vendor == MfVendor::Amf   ? 3
                      : p_->vendor == MfVendor::Software ? 4
                                                      : 0;
        return (p_->av1 ? av1_base : (p_->hevc ? hevc_base : h264_base)) + v;
    }

    bool MfEncoder::accepts_textures() const noexcept { return p_ && p_->texture; }

    HRESULT MfEncoder::init_hr() const noexcept { return p_ ? p_->init_hr : E_FAIL; }

    bool probe_mf_encoder(MfCodec codec, MfVendor vendor, int w, int h, int fps, uint32_t bps, HRESULT *hr_out,
                          std::string *err_out)
    {
        if (hr_out)
            *hr_out = S_OK;
        std::string err;
        auto report = [&]() { if (err_out) *err_out = err; return false; };
        // Detection must exercise the same system-memory path the engine falls back to.
        // Passing a D3D device here would attach a DXGI manager on matching MFTs and probe GPU-only behaviour.
        ObjectPool<PacketRef> probe_packets{256, 4096};
        auto enc = MfEncoder::create(codec, vendor, nullptr, w, h, fps, bps, Rate::Cbr, Preset::Balanced,
                                     &probe_packets, &err);
        if (!enc)
        {
            if (hr_out)
                *hr_out = E_FAIL;
            return report();
        }
        w &= ~1;
        h &= ~1;
        std::vector<uint8_t> yp((size_t)w * h, 16), uvp((size_t)w * h / 2, 128);
        std::vector<Ref<PacketRef>> out;
        const int64_t dur = SECOND_100NS / std::max(1, fps);
        for (int i = 0; i < 12; ++i)
        {
            if (!enc->encode_memory(yp.data(), w, uvp.data(), w, i * dur, i == 0, out, &err))
                return report();
            for (auto &f : out)
                if (f && !f->payload.empty())
                    return true;
            Sleep(5);
        }
        if (!enc->flush(out, &err))
            return report();
        for (auto &f : out)
            if (f && !f->payload.empty())
                return true;
        err = "hardware MFT produced no encoded output";
        return report();
    }

    VideoOptions options_from_pref(int pref, int w, int h, int fps, uint32_t bps)
    {
        VideoOptions o;
        // pref layout: bits 0..7 encoder, bit 8 rate, bit 9 buffer method,
        // bits 12..14 preset, bits 15..16 codec, bits 24..31 compact availability.
        switch (pref & 0xff)
        {
        case 5: o.enc = Enc::MfQsv; break;
        case 6: o.enc = Enc::MfVp12; break;
        case 7: o.enc = Enc::MfNvenc; break;
        case 8: o.enc = Enc::MfAmf; break;
        case 11: o.enc = Enc::MfSoftware; break;
        default: o.enc = Enc::Auto; break;
        }
        o.rate = (pref & 0x100) ? Rate::Vbr : Rate::Cbr;
        o.segmented = (pref & 0x200) != 0;
        o.preset = (Preset)std::clamp((pref >> 12) & 7, 0, 6);
        const int codec_bits = (pref >> 15) & 3;
        o.codec = codec_bits == 1   ? CodecSel::Hevc
                  : codec_bits == 2 ? CodecSel::H264
                  : codec_bits == 3 ? CodecSel::Av1
                                    : CodecSel::Auto;
        o.w = w & ~1;
        o.h = h & ~1;
        o.fps = std::max(1, fps);
        o.bps = bps;
        o.avail = expand_availability((uint8_t)(pref >> 24), o.codec);
        return o;
    }

    struct PcmToS16Converter::Impl
    {
        int rate = 0, channels = 0, bits = 0;
        bool floating = false, direct = false, copy = false, ready = false;
        ComPtr<IMFTransform> resampler;
    };

    PcmToS16Converter::PcmToS16Converter() : impl_(std::make_unique<Impl>()) {}
    PcmToS16Converter::~PcmToS16Converter() = default;

    bool PcmToS16Converter::initialize(int src_rate, int src_channels, bool src_float, int src_bits,
                                       std::string *err)
    {
        if (!impl_ || src_rate <= 0 || src_channels <= 0 || src_bits <= 0)
        {
            if (err)
                *err = "audio conversion input is invalid";
            return false;
        }

        impl_->rate = src_rate;
        impl_->channels = src_channels;
        impl_->floating = src_float;
        impl_->bits = src_bits;
        impl_->direct = src_rate == (int)AUDIO_RATE && src_channels == (int)AUDIO_CHANNELS &&
                        (src_bits == 16 || (src_float && src_bits == 32));
        impl_->copy = impl_->direct && !src_float && src_bits == 16;
        impl_->resampler.Reset();
        impl_->ready = false;

        // The common device-mix case is 48 kHz stereo float or s16. Convert it
        // directly: no resampler latency, no per-packet MFT setup, no phase resets.
        if (impl_->direct)
        {
            impl_->ready = true;
            return true;
        }

        MfRuntime &rt = mf_runtime();
        if (FAILED(rt.com_hr) || FAILED(rt.mf_hr))
        {
            if (err)
                *err = "Media Foundation is unavailable for audio conversion";
            return false;
        }

        auto make_type = [](GUID subtype, int channels, int rate, int bits, bool floating,
                            IMFMediaType **type) -> HRESULT
        {
            ComPtr<IMFMediaType> t;
            HRESULT h = MFCreateMediaType(&t);
            if (FAILED(h) || !t)
                return FAILED(h) ? h : E_FAIL;
            t->SetGUID(MF_MT_MAJOR_TYPE, MFMediaType_Audio);
            t->SetGUID(MF_MT_SUBTYPE, subtype);
            t->SetUINT32(MF_MT_AUDIO_NUM_CHANNELS, (UINT32)channels);
            t->SetUINT32(MF_MT_AUDIO_SAMPLES_PER_SECOND, (UINT32)rate);
            t->SetUINT32(MF_MT_AUDIO_BITS_PER_SAMPLE, (UINT32)bits);
            t->SetUINT32(MF_MT_AUDIO_BLOCK_ALIGNMENT, (UINT32)(channels * bits / 8));
            t->SetUINT32(MF_MT_AUDIO_AVG_BYTES_PER_SECOND,
                         (UINT32)((int64_t)rate * channels * bits / 8));
            t->SetUINT32(MF_MT_ALL_SAMPLES_INDEPENDENT, TRUE);
            if (floating)
                t->SetUINT32(MF_MT_AUDIO_FLOAT_SAMPLES_PER_SECOND, (UINT32)rate);
            *type = t.Detach();
            return S_OK;
        };

        ComPtr<IMFTransform> resampler;
        HRESULT hr = CoCreateInstance(CLSID_CResamplerMediaObject, nullptr, CLSCTX_INPROC_SERVER,
                                      IID_PPV_ARGS(&resampler));
        ComPtr<IMFMediaType> in_t, out_t;
        if (SUCCEEDED(hr))
            hr = make_type(src_float ? MFAudioFormat_Float : MFAudioFormat_PCM, src_channels, src_rate,
                           src_float ? 32 : 16, src_float, &in_t);
        if (SUCCEEDED(hr))
            hr = make_type(MFAudioFormat_PCM, (int)AUDIO_CHANNELS, (int)AUDIO_RATE, 16, false, &out_t);
        if (SUCCEEDED(hr))
            hr = resampler->SetInputType(0, in_t.Get(), 0);
        if (SUCCEEDED(hr))
            hr = resampler->SetOutputType(0, out_t.Get(), 0);
        if (FAILED(hr))
        {
            if (err)
            {
                char m[96];
                std::snprintf(m, sizeof(m), "audio resampler setup failed (0x%08X)", (unsigned)hr);
                *err = m;
            }
            return false;
        }

        resampler->ProcessMessage(MFT_MESSAGE_NOTIFY_BEGIN_STREAMING, 0);
        resampler->ProcessMessage(MFT_MESSAGE_NOTIFY_START_OF_STREAM, 0);
        impl_->resampler = resampler;
        impl_->ready = true;
        return true;
    }

    void PcmToS16Converter::reset()
    {
        if (!impl_ || !impl_->resampler)
            return;
        impl_->resampler->ProcessMessage(MFT_MESSAGE_COMMAND_FLUSH, 0);
        impl_->resampler->ProcessMessage(MFT_MESSAGE_NOTIFY_START_OF_STREAM, 0);
    }

    bool PcmToS16Converter::convert(const uint8_t *src, uint32_t frames, std::vector<int16_t> *out,
                                    std::string *err)
    {
        if (!impl_ || !out || !impl_->ready)
        {
            if (err)
                *err = "audio converter is not initialized";
            return false;
        }
        out->clear();
        if (!frames)
            return true;
        if (!src)
        {
            if (err)
                *err = "audio conversion input is invalid";
            return false;
        }

        if (impl_->direct)
        {
            out->resize((size_t)frames * AUDIO_CHANNELS);
            if (impl_->copy)
            {
                std::memcpy(out->data(), src, (size_t)frames * AUDIO_CHANNELS * sizeof(int16_t));
                return true;
            }
            const float *f = reinterpret_cast<const float *>(src);
            for (uint32_t frame = 0; frame < frames; ++frame)
            {
                for (uint32_t ch = 0; ch < AUDIO_CHANNELS; ++ch)
                {
                    float v = f[(size_t)frame * impl_->channels + ch];
                    if (!std::isfinite(v))
                        v = 0.0f;
                    v = std::clamp(v, -1.0f, 1.0f);
                    long long q = std::llround((double)v * 32767.0);
                    (*out)[(size_t)frame * AUDIO_CHANNELS + ch] =
                        (int16_t)std::clamp(q, -32768LL, 32767LL);
                }
            }
            return true;
        }

        const size_t sample_bytes = impl_->floating ? 4 : 2;
        const DWORD input_bytes = (DWORD)((size_t)frames * impl_->channels * sample_bytes);
        ComPtr<IMFMediaBuffer> in_buf;
        ComPtr<IMFSample> in_sample;
        BYTE *dst = nullptr;
        HRESULT hr = MFCreateMemoryBuffer(input_bytes, &in_buf);
        if (SUCCEEDED(hr))
            hr = in_buf->Lock(&dst, nullptr, nullptr);
        if (FAILED(hr) || !dst)
        {
            if (err)
                *err = "audio resampler input allocation failed";
            return false;
        }
        std::memcpy(dst, src, input_bytes);
        in_buf->Unlock();
        in_buf->SetCurrentLength(input_bytes);
        hr = MFCreateSample(&in_sample);
        if (SUCCEEDED(hr) && in_sample)
        {
            in_sample->AddBuffer(in_buf.Get());
            in_sample->SetSampleDuration(0); // resampler ignores sample timing
        }
        if (FAILED(hr) || !in_sample)
        {
            if (err)
                *err = "audio resampler sample allocation failed";
            return false;
        }

        hr = impl_->resampler->ProcessInput(0, in_sample.Get(), 0);
        if (FAILED(hr))
        {
            if (err)
            {
                char m[96];
                std::snprintf(m, sizeof(m), "audio resampler ProcessInput failed (0x%08X)", (unsigned)hr);
                *err = m;
            }
            return false;
        }

        std::vector<uint8_t> pcm;
        for (;;)
        {
            MFT_OUTPUT_DATA_BUFFER ob = {};
            ComPtr<IMFSample> own;
            ComPtr<IMFMediaBuffer> mb;
            if (FAILED(MFCreateSample(&own)) || !own || FAILED(MFCreateMemoryBuffer(65536, &mb)) || !mb)
                break;
            own->AddBuffer(mb.Get());
            ob.pSample = own.Get();
            DWORD status = 0;
            hr = impl_->resampler->ProcessOutput(0, 1, &ob, &status);
            if (hr == MF_E_TRANSFORM_NEED_MORE_INPUT || FAILED(hr))
                break;
            ComPtr<IMFMediaBuffer> data;
            if (SUCCEEDED(own->ConvertToContiguousBuffer(&data)) && data)
            {
                BYTE *bytes = nullptr;
                DWORD len = 0;
                if (SUCCEEDED(data->Lock(&bytes, nullptr, &len)) && bytes)
                {
                    pcm.insert(pcm.end(), bytes, bytes + len);
                    data->Unlock();
                }
            }
            if (ob.pEvents)
                ob.pEvents->Release();
        }
        if (pcm.size() >= 2)
        {
            out->resize(pcm.size() / 2);
            std::memcpy(out->data(), pcm.data(), out->size() * sizeof(int16_t));
        }
        return true;
    }

    bool select_video(const VideoOptions &o, VideoSelection *out, std::string *err)
    {
        if (!out)
            return false;
        out->mf = o.codec == CodecSel::Hevc   ? MfCodec::Hevc
                  : o.codec == CodecSel::Av1 ? MfCodec::Av1
                                             : MfCodec::H264;

        auto choose = [&](MfVendor vendor, const char *why)
        {
            const uint32_t bit = mf_bit_for(out->mf, vendor);
            if (o.avail && !(o.avail & bit))
                return fail_selection(err, std::string(mf_vendor_name(vendor)) + " did not produce " +
                                               std::string(codec_label(o.codec)) + " output in the probe.");
            out->mf_vendor = vendor;
            return true;
        };

        switch (o.enc)
        {
        case Enc::MfQsv: return choose(MfVendor::Qsv, "explicit");
        case Enc::MfVp12: return choose(MfVendor::Vp12, "explicit");
        case Enc::MfNvenc: return choose(MfVendor::Nvenc, "explicit");
        case Enc::MfAmf: return choose(MfVendor::Amf, "explicit");
        case Enc::MfSoftware: return choose(MfVendor::Software, "explicit");
        case Enc::Auto:
        default:
            break;
        }

        // Auto keeps the historical hardware preference order, then the
        // system-memory MFT. engine.cpp retries the remaining vendors if the
        // first choice cannot be opened on this machine.
        const MfVendor order[] = {MfVendor::Qsv, MfVendor::Vp12, MfVendor::Nvenc, MfVendor::Amf,
                                  MfVendor::Software};
        for (MfVendor vendor : order)
        {
            if (!o.avail || (o.avail & mf_bit_for(out->mf, vendor)))
            {
                out->mf_vendor = vendor;
                return true;
            }
        }
        return fail_selection(err, std::string(codec_label(o.codec)) +
                                       " has no available Media Foundation encoder on this machine.");
    }

    // -------------------------------------------------------------------------
    // Save: Media Foundation SinkWriter (MP4 only). Compressed video packets
    // from the MFT are passed straight through; the captured 48 kHz stereo PCM
    // is transcoded to AAC by the writer's internal audio encoder.
    // -------------------------------------------------------------------------
    namespace
    {
        // Walk Annex-B start codes. Returns NAL [start, end) with the start code
        // included so parameter sets can be copied verbatim into the header blob.
        bool next_annexb_nal(const uint8_t *d, size_t n, size_t &pos, size_t &nal_start, size_t &nal_end)
        {
            nal_start = nal_end = n;
            while (pos + 3 <= n)
            {
                if (d[pos] == 0 && d[pos + 1] == 0 && d[pos + 2] == 1)
                    break;
                if (pos + 4 <= n && d[pos] == 0 && d[pos + 1] == 0 && d[pos + 2] == 0 && d[pos + 3] == 1)
                    break;
                ++pos;
            }
            if (pos + 3 > n)
                return false;
            nal_start = pos;
            const size_t sc = (pos + 3 <= n && d[pos] == 0 && d[pos + 1] == 0 && d[pos + 2] == 1) ? 3 : 4;
            pos += sc;
            size_t e = pos;
            while (e + 3 <= n)
            {
                if (d[e] == 0 && d[e + 1] == 0 && d[e + 2] == 1)
                    break;
                if (e + 4 <= n && d[e] == 0 && d[e + 1] == 0 && d[e + 2] == 0 && d[e + 3] == 1)
                    break;
                ++e;
            }
            nal_end = e;
            pos = e;
            return true;
        }

        // Collect VPS/SPS/PPS (HEVC) or SPS/PPS (H.264) from a keyframe's
        // Annex-B access unit. This becomes MF_MT_MPEG_SEQUENCE_HEADER.
        std::vector<uint8_t> collect_param_sets(const uint8_t *d, size_t n, bool hevc)
        {
            std::vector<uint8_t> out;
            if (!d || n < 4)
                return out;
            size_t pos = 0;
            while (pos < n)
            {
                size_t s = 0, e = 0;
                if (!next_annexb_nal(d, n, pos, s, e) || s >= e || e > n)
                    break;
                const size_t sc = (s + 3 <= n && d[s] == 0 && d[s + 1] == 0 && d[s + 2] == 1) ? 3 : 4;
                if (s + sc >= e)
                    continue;
                bool keep = false;
                if (hevc)
                {
                    const uint8_t type = (d[s + sc] >> 1) & 0x3f;
                    keep = type == 32 || type == 33 || type == 34; // VPS, SPS, PPS
                }
                else
                {
                    const uint8_t type = d[s + sc] & 0x1f;
                    keep = type == 7 || type == 8; // SPS, PPS
                }
                if (keep)
                    out.insert(out.end(), d + s, d + e);
            }
            return out;
        }

        // OBU_SEQUENCE_HEADER (type 1) from an AV1 keyframe, with its 1- or
        // 2-byte length header included so the MP4 writer sees a valid OBU.
        std::vector<uint8_t> extract_av1_sequence_obu(const uint8_t *d, size_t n)
        {
            std::vector<uint8_t> out;
            size_t i = 0;
            while (i + 1 < n)
            {
                const uint8_t h = d[i];
                if (h & 0x80)
                    return out; // forbidden bit: stop
                const bool has_size = (h & 0x02) != 0;
                size_t len = 0, bytes = 0;
                size_t p = i + 1;
                if (has_size)
                {
                    // leb128
                    for (int k = 0; k < 8 && p < n; ++k, ++p)
                    {
                        len |= (size_t)(d[p] & 0x7f) << (7 * k);
                        if (!(d[p] & 0x80))
                        {
                            ++p;
                            break;
                        }
                    }
                    bytes = p - i;
                }
                else
                {
                    len = n - p;
                    bytes = 1;
                }
                const uint8_t type = (h >> 3) & 0x0f;
                if (len == 0 || p + len > n)
                    return out;
                if (type == 1)
                {
                    out.assign(d + i, d + p + len);
                    return out;
                }
                i = p + len;
            }
            return out;
        }

        HRESULT create_memory_sample(const uint8_t *data, size_t size, int64_t pts100ns, int64_t duration100ns,
                                     bool clean, IMFSample **out)
        {
            if (!out || !data || !size)
                return E_INVALIDARG;
            ComPtr<IMFMediaBuffer> buffer;
            HRESULT hr = MFCreateMemoryBuffer((DWORD)size, &buffer);
            if (FAILED(hr) || !buffer)
                return FAILED(hr) ? hr : E_FAIL;
            BYTE *dst = nullptr;
            hr = buffer->Lock(&dst, nullptr, nullptr);
            if (FAILED(hr) || !dst)
                return FAILED(hr) ? hr : E_FAIL;
            std::memcpy(dst, data, size);
            buffer->Unlock();
            buffer->SetCurrentLength((DWORD)size);

            ComPtr<IMFSample> sample;
            hr = MFCreateSample(&sample);
            if (FAILED(hr) || !sample)
                return FAILED(hr) ? hr : E_FAIL;
            hr = sample->AddBuffer(buffer.Get());
            if (FAILED(hr))
                return hr;
            hr = sample->SetSampleTime(pts100ns);
            if (FAILED(hr))
                return hr;
            hr = sample->SetSampleDuration(duration100ns);
            if (FAILED(hr))
                return hr;
            if (clean)
                sample->SetUINT32(MFSampleExtension_CleanPoint, 1);
            *out = sample.Detach();
            return S_OK;
        }
    } // namespace

    int write_mf_file(const std::wstring &path, const std::vector<Ref<PacketRef>> &video,
                      const std::vector<AudioChunk> &audio, CodecSel codec, int fps, int w, int h, int seconds_back,
                      int64_t end_time, bool segmented)
    {
        auto fail = [](const char *m)
        { set_last_error(m); return IR_FAIL; };

        MfRuntime &rt = mf_runtime();
        if (FAILED(rt.com_hr) || FAILED(rt.mf_hr))
            return fail("Media Foundation is unavailable for saving.");

        std::vector<const PacketRef *> pkts;
        pkts.reserve(video.size());
        for (const auto &p : video)
            if (p && !p->payload.empty())
                pkts.push_back(p.get());
        if (pkts.empty())
            return IR_NOT_ENOUGH_DATA;

        fps = std::max(1, fps);
        w = std::max(2, w);
        h = std::max(2, h);
        const int64_t requested_duration =
            seconds_back > 0 ? (int64_t)seconds_back * SECOND_100NS : 0;
        const int64_t trim_start = seconds_back > 0 ? end_time - requested_duration : INT64_MIN;

        std::vector<size_t> key_indices;
        key_indices.reserve(pkts.size());
        for (size_t i = 0; i < pkts.size(); ++i)
            if (pkts[i]->keyframe)
                key_indices.push_back(i);

        size_t start = 0;
        if (seconds_back > 0)
        {
            long before = -1;
            for (size_t i = 0; i < pkts.size(); ++i)
            {
                if (pkts[i]->pts100ns > trim_start)
                    break;
                if (pkts[i]->keyframe)
                    before = (long)i;
            }
            if (before >= 0)
                start = (size_t)before;
            else if (!key_indices.empty())
                start = key_indices.front();
        }

        // Segmented mode forces one IDR per second. Pick exactly the requested
        // number of one-second segments ending at the save boundary; choosing
        // every keyframe from the old GOP-aligned start added a whole segment.
        std::vector<int64_t> seg_starts;
        bool exact_cap = false;
        if (segmented)
        {
            size_t seg_first = 0;
            if (seconds_back > 0 && !key_indices.empty())
            {
                size_t at_or_after = 0;
                while (at_or_after < key_indices.size() &&
                       pkts[key_indices[at_or_after]]->pts100ns <= trim_start)
                    ++at_or_after;
                seg_first = at_or_after > 0 ? at_or_after - 1 : 0;
                const size_t needed = (size_t)seconds_back;
                if (key_indices.size() - seg_first >= needed)
                {
                    exact_cap = true;
                    start = key_indices[seg_first];
                    for (size_t i = 0; i < needed; ++i)
                        seg_starts.push_back(pkts[key_indices[seg_first + i]]->pts100ns);
                }
                else
                {
                    start = key_indices[seg_first];
                    for (size_t i = seg_first; i < key_indices.size(); ++i)
                        seg_starts.push_back(pkts[key_indices[i]]->pts100ns);
                }
            }
            else
            {
                for (size_t i = 0; i < key_indices.size(); ++i)
                {
                    if (key_indices[i] >= start)
                    {
                        for (; i < key_indices.size(); ++i)
                            seg_starts.push_back(pkts[key_indices[i]]->pts100ns);
                        break;
                    }
                }
            }
            if (seg_starts.empty())
                seg_starts.push_back(pkts[start]->pts100ns);
        }

        const size_t count = pkts.size() - start;
        const int64_t first_pts = pkts[start]->pts100ns;
        const int64_t frame_dur = SECOND_100NS / fps;
        const int64_t last_end = std::max(end_time, pkts[start + count - 1]->pts100ns + frame_dur);
        if (last_end - first_pts < SECOND_100NS / 2)
            return IR_NOT_ENOUGH_DATA;

        // In continuous mode the previous keyframe can be up to one two-second
        // GOP before the requested start. Keep it as the decode pre-roll, but
        // stamp everything before the requested start at zero so the output
        // timeline still ends at exactly X seconds.
        if (!segmented && seconds_back > 0 &&
            end_time - first_pts >= requested_duration - std::min<int64_t>(SECOND_100NS, 2 * frame_dur))
            exact_cap = true;

        const int64_t out_end = exact_cap && !segmented
                                    ? requested_duration
                                    : (segmented ? (int64_t)seg_starts.size() * SECOND_100NS
                                                 : std::max<int64_t>(0, last_end - first_pts));

        auto mapped_video_pts = [&](int64_t pts) -> int64_t
        {
            if (segmented)
            {
                const auto it = std::upper_bound(seg_starts.begin(), seg_starts.end(), pts);
                const size_t si = it == seg_starts.begin() ? 0 : (size_t)(it - seg_starts.begin() - 1);
                const int64_t origin = seg_starts[si];
                int64_t rel = std::max<int64_t>(0, pts - origin);
                const int64_t next = si + 1 < seg_starts.size() ? seg_starts[si + 1] : end_time;
                const int64_t limit = std::min<int64_t>(SECOND_100NS, std::max<int64_t>(1, next - origin));
                if (limit > 0 && rel >= limit)
                    rel = limit > frame_dur ? limit - frame_dur : 0;
                return std::clamp<int64_t>((int64_t)si * SECOND_100NS + rel, 0, out_end - 1);
            }
            if (exact_cap)
            {
                if (pts <= trim_start)
                    return 0;
                return std::clamp<int64_t>(pts - trim_start, 0, out_end - 1);
            }
            return std::max<int64_t>(0, pts - first_pts);
        };
        struct TimeRange
        {
            int64_t begin;
            int64_t end;
            int64_t out_base;
        };
        std::vector<TimeRange> audio_ranges;
        if (segmented)
        {
            for (size_t i = 0; i < seg_starts.size(); ++i)
            {
                const int64_t next = i + 1 < seg_starts.size() ? seg_starts[i + 1] : end_time;
                const int64_t end = std::min(next, seg_starts[i] + SECOND_100NS);
                if (end > seg_starts[i])
                    audio_ranges.push_back({seg_starts[i], end, (int64_t)i * SECOND_100NS});
            }
        }
        else if (exact_cap)
            audio_ranges.push_back({trim_start, end_time, 0});
        else
            audio_ranges.push_back({first_pts, last_end, 0});

        const bool av1 = codec == CodecSel::Av1;
        const bool hevc = codec == CodecSel::Hevc;
        const GUID subtype = mf_codec_subtype(av1 ? MfCodec::Av1 : (hevc ? MfCodec::Hevc : MfCodec::H264));

        std::vector<uint8_t> seq_header;
        for (size_t i = start; i < pkts.size(); ++i)
        {
            if (!pkts[i]->keyframe)
                continue;
            const auto &p = *pkts[i];
            if (av1)
                seq_header = extract_av1_sequence_obu(p.payload.data(), p.payload.size());
            else if (p.codec_data > 0 && p.codec_data <= p.payload.size())
                seq_header.assign(p.payload.data(), p.payload.data() + p.codec_data);
            else
                seq_header = collect_param_sets(p.payload.data(), p.payload.size(), hevc);
            if (!seq_header.empty())
                break;
        }
        if (seq_header.empty())
            return fail(av1 ? "The buffered AV1 video has no sequence-header OBU."
                            : "The buffered video has no SPS/PPS (or VPS) parameter sets.");

        // MP4 container only. The path extension is .mp4; the attribute makes
        // the choice explicit even when the caller supplies a different name.
        ComPtr<IMFAttributes> attrs;
        HRESULT hr = MFCreateAttributes(&attrs, 2);
        if (SUCCEEDED(hr))
            hr = attrs->SetGUID(MF_TRANSCODE_CONTAINERTYPE, MFTranscodeContainerType_MPEG4);
        ComPtr<IMFSinkWriter> writer;
        if (SUCCEEDED(hr))
            hr = MFCreateSinkWriterFromURL(path.c_str(), nullptr, attrs.Get(), &writer);
        if (FAILED(hr) || !writer)
        {
            char m[160];
            std::snprintf(m, sizeof(m), "Could not create the MP4 writer (0x%08X).", (unsigned)hr);
            return fail(m);
        }

        // Compressed video stream. Passing the encoded subtype makes this a
        // passthrough stream; MF converts Annex-B to the container's format.
        ComPtr<IMFMediaType> vtype;
        hr = MFCreateMediaType(&vtype);
        if (SUCCEEDED(hr))
            hr = vtype->SetGUID(MF_MT_MAJOR_TYPE, MFMediaType_Video);
        if (SUCCEEDED(hr))
            hr = vtype->SetGUID(MF_MT_SUBTYPE, subtype);
        if (SUCCEEDED(hr))
            hr = vtype->SetUINT32(MF_MT_AVG_BITRATE, 12000000);
        if (SUCCEEDED(hr))
            hr = MFSetAttributeSize(vtype.Get(), MF_MT_FRAME_SIZE, (UINT32)w, (UINT32)h);
        if (SUCCEEDED(hr))
            hr = MFSetAttributeRatio(vtype.Get(), MF_MT_FRAME_RATE, (UINT32)fps, 1);
        if (SUCCEEDED(hr))
            hr = MFSetAttributeRatio(vtype.Get(), MF_MT_PIXEL_ASPECT_RATIO, 1, 1);
        if (SUCCEEDED(hr))
            hr = vtype->SetUINT32(MF_MT_INTERLACE_MODE, MFVideoInterlace_Progressive);
        if (!av1 && SUCCEEDED(hr))
            hr = vtype->SetBlob(MF_MT_MPEG_SEQUENCE_HEADER, seq_header.data(), (UINT32)seq_header.size());

        DWORD video_stream = 0;
        if (SUCCEEDED(hr))
            hr = writer->AddStream(vtype.Get(), &video_stream);
        if (SUCCEEDED(hr))
            hr = writer->SetInputMediaType(video_stream, vtype.Get(), nullptr);
        if (FAILED(hr))
        {
            DeleteFileW(path.c_str());
            char m[160];
            std::snprintf(m, sizeof(m), "Could not configure the MP4 video stream (0x%08X).", (unsigned)hr);
            return fail(m);
        }

        // PCM audio stream. AddStream takes the target (AAC) type and
        // SetInputMediaType takes the PCM we actually write; that is what makes
        // the sink writer insert the AAC encoder. Passing PCM to AddStream
        // makes the sink accept raw PCM and fail at Finalize with
        // MF_E_SINK_HEADERS_NOT_FOUND.
        DWORD audio_stream = 0;
        bool have_audio = false;
        if (!audio.empty())
        {
            ComPtr<IMFMediaType> aac_type;
            hr = MFCreateMediaType(&aac_type);
            if (SUCCEEDED(hr))
                hr = aac_type->SetGUID(MF_MT_MAJOR_TYPE, MFMediaType_Audio);
            if (SUCCEEDED(hr))
                hr = aac_type->SetGUID(MF_MT_SUBTYPE, MFAudioFormat_AAC);
            if (SUCCEEDED(hr))
                hr = aac_type->SetUINT32(MF_MT_AUDIO_BITS_PER_SAMPLE, 16);
            if (SUCCEEDED(hr))
                hr = aac_type->SetUINT32(MF_MT_AUDIO_SAMPLES_PER_SECOND, (UINT32)AUDIO_RATE);
            if (SUCCEEDED(hr))
                hr = aac_type->SetUINT32(MF_MT_AUDIO_NUM_CHANNELS, (UINT32)AUDIO_CHANNELS);
            if (SUCCEEDED(hr))
                hr = aac_type->SetUINT32(MF_MT_AUDIO_AVG_BYTES_PER_SECOND, 24000);
            if (SUCCEEDED(hr))
                hr = aac_type->SetUINT32(MF_MT_AAC_PAYLOAD_TYPE, 0);
            if (SUCCEEDED(hr))
                hr = writer->AddStream(aac_type.Get(), &audio_stream);

            ComPtr<IMFMediaType> atype;
            if (SUCCEEDED(hr))
                hr = MFCreateMediaType(&atype);
            if (SUCCEEDED(hr))
                hr = atype->SetGUID(MF_MT_MAJOR_TYPE, MFMediaType_Audio);
            if (SUCCEEDED(hr))
                hr = atype->SetGUID(MF_MT_SUBTYPE, MFAudioFormat_PCM);
            if (SUCCEEDED(hr))
                hr = atype->SetUINT32(MF_MT_AUDIO_NUM_CHANNELS, (UINT32)AUDIO_CHANNELS);
            if (SUCCEEDED(hr))
                hr = atype->SetUINT32(MF_MT_AUDIO_SAMPLES_PER_SECOND, (UINT32)AUDIO_RATE);
            if (SUCCEEDED(hr))
                hr = atype->SetUINT32(MF_MT_AUDIO_BITS_PER_SAMPLE, 16);
            if (SUCCEEDED(hr))
                hr = atype->SetUINT32(MF_MT_AUDIO_BLOCK_ALIGNMENT, (UINT32)(AUDIO_CHANNELS * 2));
            if (SUCCEEDED(hr))
                hr = atype->SetUINT32(MF_MT_AUDIO_AVG_BYTES_PER_SECOND,
                                      (UINT32)((int64_t)AUDIO_RATE * AUDIO_CHANNELS * 2));
            if (SUCCEEDED(hr))
                hr = atype->SetUINT32(MF_MT_ALL_SAMPLES_INDEPENDENT, TRUE);
            if (SUCCEEDED(hr))
                hr = writer->SetInputMediaType(audio_stream, atype.Get(), nullptr);
            if (FAILED(hr))
            {
                DeleteFileW(path.c_str());
                char m[160];
                std::snprintf(m, sizeof(m), "Could not configure the MP4 audio stream (0x%08X).", (unsigned)hr);
                return fail(m);
            }
            have_audio = true;
        }

        hr = writer->BeginWriting();
        if (FAILED(hr))
        {
            DeleteFileW(path.c_str());
            char m[160];
            std::snprintf(m, sizeof(m), "Could not begin writing the MP4 file (0x%08X).", (unsigned)hr);
            return fail(m);
        }

        // The MP4 sink interleaves its streams. It will not drain video
        // samples while the audio stream has no data for the same time range,
        // so writing every video sample first and the audio afterwards stalls
        // once the sink's queue fills. Build both queues up front and submit
        // them in ascending PTS order, splitting audio into short chunks.
        struct VideoWrite
        {
            int64_t pts;
            const uint8_t *data;
            size_t size;
            bool key;
            int64_t duration;
        };
        struct AudioWrite
        {
            int64_t pts;
            const uint8_t *data;
            size_t bytes;
            int64_t duration;
        };

        std::vector<VideoWrite> video_writes;
        video_writes.reserve(count);
        int64_t previous = -1;
        for (size_t i = start; i < pkts.size(); ++i)
        {
            const auto &p = *pkts[i];
            int64_t pts = mapped_video_pts(p.pts100ns);
            if (pts <= previous)
                pts = previous + 1;
            previous = pts;
            const size_t pre_skip = av1 ? 0 : std::min(p.codec_data, p.payload.size());
            const size_t n = p.payload.size() - pre_skip;
            if (!n)
                continue;
            video_writes.push_back({pts, p.payload.data() + pre_skip, n, p.keyframe, frame_dur});
        }
        // The sink derives the MP4 sample table from these durations. Spreading
        // the final partial interval across the last sample is what closes the
        // requested X-second cap instead of rounding to a whole GOP.
        for (size_t i = 0; i < video_writes.size(); ++i)
        {
            if (!exact_cap && !segmented)
                continue;
            const int64_t next = i + 1 < video_writes.size() ? video_writes[i + 1].pts : out_end;
            video_writes[i].duration = std::clamp<int64_t>(next - video_writes[i].pts, 1,
                                                           out_end - video_writes[i].pts);
        }

        std::vector<AudioWrite> audio_writes;
        std::vector<int16_t> audio_silence; // backs inserted silence writes through the write loop
        if (have_audio)
        {
            // Half-second PCM chunks (24 000 frames at 48 kHz) keep the
            // interleaver fed without building one multi-megabyte sample.
            const int64_t chunk_frames = std::max<int64_t>(1, AUDIO_RATE / 2);
            auto ticks_from_frames = [](int64_t frames) -> int64_t
            {
                return frames * SECOND_100NS / AUDIO_RATE;
            };
            auto frames_from_ticks = [](int64_t ticks) -> int64_t
            {
                return ticks * AUDIO_RATE / SECOND_100NS;
            };
            auto ceil_frames = [&](int64_t delta) -> int64_t
            {
                return (delta * AUDIO_RATE + SECOND_100NS - 1) / SECOND_100NS;
            };
            const int64_t range_begin = audio_ranges.front().begin;
            const int64_t range_end = audio_ranges.back().end;
            for (const auto &c : audio)
            {
                if (!c.data || c.frames == 0)
                    continue;
                const int64_t chunk_end = c.pts100ns + ticks_from_frames(c.frames);
                if (chunk_end <= range_begin || c.pts100ns >= range_end)
                    continue;
                for (const auto &range : audio_ranges)
                {
                    const int64_t from = std::max(c.pts100ns, range.begin);
                    const int64_t to = std::min(chunk_end, range.end);
                    if (to <= from)
                        continue;
                    int64_t off = ceil_frames(from - c.pts100ns);
                    int64_t stop = ceil_frames(to - c.pts100ns);
                    off = std::clamp<int64_t>(off, 0, c.frames);
                    stop = std::clamp<int64_t>(stop, 0, c.frames);
                    const int64_t span = range.end - range.begin;
                    for (int64_t at = off; at < stop; at += chunk_frames)
                    {
                        const int64_t frames = std::min(chunk_frames, stop - at);
                        int64_t rel_frames = frames_from_ticks(
                            std::max<int64_t>(0, c.pts100ns + ticks_from_frames(at) - range.begin));
                        const int64_t span_frames = frames_from_ticks(span);
                        if (rel_frames >= span_frames)
                            rel_frames = span_frames > 1 ? span_frames - 1 : 0;
                        audio_writes.push_back({range.out_base + ticks_from_frames(rel_frames),
                                                c.data + (size_t)at * AUDIO_CHANNELS * sizeof(int16_t),
                                                (size_t)frames * AUDIO_CHANNELS * sizeof(int16_t),
                                                ticks_from_frames(frames)});
                    }
                }
            }

            // Keyframe spacing or a short WASAPI outage can leave holes in the
            // selected audio timeline. Fill them with real silence samples so the
            // AAC encoder never sees an abrupt start/stop at a range boundary.
            std::sort(audio_writes.begin(), audio_writes.end(),
                      [](const AudioWrite &a, const AudioWrite &b) { return a.pts < b.pts; });
            audio_silence.assign((size_t)chunk_frames * AUDIO_CHANNELS, 0);
            std::vector<AudioWrite> filled;
            filled.reserve(audio_writes.size() + (size_t)(out_end / SECOND_100NS) * 2 + 2);
            int64_t cursor = 0;
            auto add_silence = [&](int64_t from, int64_t to)
            {
                // Keep the existing "real gap" rule for source restarts; only
                // bridge short holes that are jitter or a missed packet.
                if (to <= from || to - from > SECOND_100NS) return;
                for (int64_t at = from; at < to;)
                {
                    const int64_t remaining = to - at;
                    int64_t frames = std::min<int64_t>(chunk_frames, ceil_frames(remaining));
                    if (frames <= 0) break;
                    int64_t duration = std::min<int64_t>(remaining, ticks_from_frames(frames));
                    filled.push_back({at, reinterpret_cast<const uint8_t *>(audio_silence.data()),
                                      (size_t)frames * AUDIO_CHANNELS * sizeof(int16_t), duration});
                    at += duration;
                }
            };
            for (const auto &a : audio_writes)
            {
                if (a.bytes == 0 || a.duration <= 0) continue;
                int64_t start = std::max<int64_t>(0, a.pts);
                if (start >= out_end) continue;
                int64_t stop = std::min<int64_t>(out_end, start + a.duration);
                if (stop <= start) continue;
                add_silence(cursor, start);

                AudioWrite write = a;
                if (stop < start + a.duration)
                {
                    const int64_t frames = frames_from_ticks(stop - start);
                    write.bytes = (size_t)frames * AUDIO_CHANNELS * sizeof(int16_t);
                    write.duration = ticks_from_frames(frames);
                }
                if (write.bytes)
                    filled.push_back(write);
                cursor = std::max(cursor, start + write.duration);
            }
            add_silence(cursor, out_end);
            audio_writes.swap(filled);
        }

        int result = IR_OK;
        size_t vi = 0, ai = 0;
        while (result == IR_OK && (vi < video_writes.size() || ai < audio_writes.size()))
        {
            const bool audio_next =
                ai < audio_writes.size() &&
                (vi >= video_writes.size() || audio_writes[ai].pts < video_writes[vi].pts);
            ComPtr<IMFSample> sample;
            if (audio_next)
            {
                const AudioWrite &a = audio_writes[ai++];
                hr = create_memory_sample(a.data, a.bytes, a.pts, a.duration, false, &sample);
                if (SUCCEEDED(hr) && sample)
                    hr = writer->WriteSample(audio_stream, sample.Get());
                if (FAILED(hr))
                    result = fail("Writing an audio sample failed.");
            }
            else
            {
                const VideoWrite &v = video_writes[vi++];
                hr = create_memory_sample(v.data, v.size, v.pts, v.duration, v.key, &sample);
                if (SUCCEEDED(hr) && sample)
                    hr = writer->WriteSample(video_stream, sample.Get());
                if (FAILED(hr))
                    result = fail("Writing a video sample failed.");
            }
        }

        if (result == IR_OK)
        {
            hr = writer->Finalize();
            if (FAILED(hr))
                result = fail("Finalizing the MP4 file failed.");
        }
        if (result != IR_OK)
            DeleteFileW(path.c_str());
        return result;
    }

