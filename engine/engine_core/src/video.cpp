        bool gen12_name(const std::wstring &lower)
        {
            // QSV v9/v10: Core Ultra (Meteor/Arrow/Lunar/Panther Lake) and Arc
            // (Alchemist/Battlemage). 11th-14th Gen are QSV v8 and stay in MF QSV.
            return name_has(lower, L"arc") || name_has(lower, L"core ultra") || name_has(lower, L"iris xe") ||
                   name_has(lower, L"gen12") || name_has(lower, L"alchemist") || name_has(lower, L"battlemage") ||
                   name_has(lower, L"meteor lake") || name_has(lower, L"arrow lake") ||
                   name_has(lower, L"lunar lake") || name_has(lower, L"panther lake");
        }

        bool intel_name(const std::wstring &lower)
        {
            return name_has(lower, L"intel") || name_has(lower, L"qsv") || name_has(lower, L"quick sync") ||
                   name_has(lower, L"iris") || gen12_name(lower);
        }

        // True when the D3D11 device selected for capture sits on an Intel
        // Gen12-class adapter (Arc / Core Ultra / Iris Xe). Used to let the
        // "MF VP12" choice find Intel MFTs whose friendly name is generic.
        bool gpu_is_gen12(const GpuContext *gpu)
        {
            if (!gpu || !gpu->dev)
                return false;
            LUID luid = {};
            if (!device_luid(gpu->dev.Get(), &luid))
                return false;
            ComPtr<IDXGIFactory1> factory;
            if (FAILED(CreateDXGIFactory1(IID_PPV_ARGS(&factory))))
                return false;
            for (UINT i = 0;; ++i)
            {
                ComPtr<IDXGIAdapter1> adapter;
                if (factory->EnumAdapters1(i, &adapter) == DXGI_ERROR_NOT_FOUND)
                    break;
                DXGI_ADAPTER_DESC1 desc = {};
                if (FAILED(adapter->GetDesc1(&desc)))
                    continue;
                if (desc.AdapterLuid.LowPart != luid.LowPart || desc.AdapterLuid.HighPart != luid.HighPart)
                    continue;
                std::wstring text(desc.Description);
                for (wchar_t &ch : text)
                    ch = (wchar_t)towlower(ch);
                return gen12_name(text);
            }
            return false;
        }

        bool vendor_matches(IMFActivate *act, MfVendor vendor, bool gen12_adapter)
        {
            const std::wstring lower = lower_name(act);
            switch (vendor)
            {
            case MfVendor::Qsv:
                return intel_name(lower);
            case MfVendor::Vp12:
                return intel_name(lower) && (gen12_name(lower) || gen12_adapter);
            case MfVendor::Nvenc:
                return name_has(lower, L"nvidia") || name_has(lower, L"nvenc");
            case MfVendor::Amf:
                return name_has(lower, L"amd") || name_has(lower, L"amf") || name_has(lower, L"radeon");
            case MfVendor::Software:
                return name_has(lower, L"microsoft") || name_has(lower, L"software");
            }
            return false;
        }

        bool activate_matches_luid(IMFActivate *act, const LUID *want)
        {
            if (!act || !want)
                return false;
            UINT32 size = 0;
            if (FAILED(act->GetBlob(MFT_ENUM_ADAPTER_LUID, nullptr, 0, &size)) || size < sizeof(LUID))
                return false;
            LUID got = {};
            UINT32 written = 0;
            if (FAILED(act->GetBlob(MFT_ENUM_ADAPTER_LUID, reinterpret_cast<UINT8 *>(&got), sizeof(got), &written)) ||
                written < sizeof(got))
                return false;
            return got.LowPart == want->LowPart && got.HighPart == want->HighPart;
        }

        // Exact vendor first, then LUID match, then Gen12 preference. Non-matching
        // vendors are removed by enumerate_mfts(), so an explicit MF choice
        // never silently switches to a different vendor.
        void rank_activates(IMFActivate **list, UINT32 count, const LUID *luid, MfVendor vendor, bool gen12_adapter)
        {
            if (!list || count < 2)
                return;
            LUID want = luid ? *luid : LUID{};
            const bool has_luid = luid != nullptr;
            std::stable_sort(list, list + count, [&](IMFActivate *a, IMFActivate *b)
                             {
                                 auto score = [&](IMFActivate *act)
                                 {
                                     int s = vendor_matches(act, vendor, gen12_adapter) ? 8 : 0;
                                     if (has_luid && activate_matches_luid(act, &want))
                                         s += 4;
                                     if (gen12_name(lower_name(act)))
                                         s += 2;
                                     return s;
                                 };
                                 return score(a) > score(b);
                             });
        }

        struct NalRange
        {
            size_t start, end;
        };

        std::vector<NalRange> annexb_units(const uint8_t *d, size_t n)
        {
            std::vector<NalRange> out;
            if (!d)
                return out;
            size_t i = 0;
            long cur = -1;
            while (i + 3 <= n)
            {
                if (d[i] == 0 && d[i + 1] == 0 && d[i + 2] == 1)
                {
                    if (cur >= 0)
                    {
                        size_t e = i;
                        while (e > (size_t)cur && d[e - 1] == 0)
                            --e;
                        out.push_back({(size_t)cur, e});
                    }
                    cur = (long)(i + 3);
                    i += 3;
                }
                else
                {
                    ++i;
                }
            }
            if (cur >= 0 && (size_t)cur < n)
                out.push_back({(size_t)cur, n});
            return out;
        }

        // Never prepend a partial header: require AVC SPS+PPS or HEVC VPS+SPS+PPS.
        bool has_complete_param_sets(const uint8_t *d, size_t n, bool hevc)
        {
            bool vps = false, sps = false, pps = false;
            for (const auto &u : annexb_units(d, n))
            {
                if (u.end <= u.start || u.start >= n)
                    continue;
                const uint8_t b = d[u.start];
                if (hevc)
                {
                    const int t = (b >> 1) & 0x3f;
                    if (t == 32)
                        vps = true;
                    else if (t == 33)
                        sps = true;
                    else if (t == 34)
                        pps = true;
                }
                else
                {
                    const int t = b & 0x1f;
                    if (t == 7)
                        sps = true;
                    else if (t == 8)
                        pps = true;
                }
            }
            return hevc ? (vps && sps && pps) : (sps && pps);
        }

        bool has_key_nal(const uint8_t *d, size_t n, bool hevc)
        {
            for (const auto &u : annexb_units(d, n))
            {
                if (u.end <= u.start || u.start >= n)
                    continue;
                const uint8_t b = d[u.start];
                const int t = hevc ? ((b >> 1) & 0x3f) : (b & 0x1f);
                if (hevc ? (t >= 16 && t <= 21) : (t == 5))
                    return true;
            }
            return false;
        }

        std::vector<uint8_t> read_seq_header(IMFTransform *mft)
        {
            std::vector<uint8_t> header;
            ComPtr<IMFMediaType> cur;
            if (FAILED(mft->GetOutputCurrentType(0, &cur)) || !cur)
                return header;
            UINT32 size = 0;
            if (FAILED(cur->GetBlobSize(MF_MT_MPEG_SEQUENCE_HEADER, &size)) || size <= 4)
                return header;
            header.resize(size);
            UINT32 written = 0;
            if (FAILED(cur->GetBlob(MF_MT_MPEG_SEQUENCE_HEADER, header.data(), size, &written)) || written <= 4)
            {
                header.clear();
                return header;
            }
            header.resize(written);
            const bool sc3 = header[0] == 0 && header[1] == 0 && header[2] == 1;
            const bool sc4 = header[0] == 0 && header[1] == 0 && header[2] == 0 && header[3] == 1;
            if (!sc3 && !sc4)
                header.clear();
            return header;
        }

